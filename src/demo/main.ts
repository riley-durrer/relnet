// One-command demo: `npm run demo` (needs a running sandbox, see README).
// Two companies' agents negotiate inside mandates their humans set, the humans sign, then the
// agents run the deal on-chain. One delivery is genuinely late, so the signed late-price rule fires.
import { Terms, summarizeTerms } from "../lib/terms.js";
import { setup } from "../lib/world.js";
import { EXAMPLE_BUYER_MANDATE, EXAMPLE_SUPPLIER_MANDATE } from "../agents/negotiate.js";
import { createIdentity, pinPeer } from "../channel/identity.js";
import { startResponder, negotiateOverA2A } from "../channel/a2a.js";
import { withinLimits } from "../channel/protocol.js";
import { randomUUID } from "node:crypto";
import { DecisionLog, buyerPlacesOrder, scaleTime, revertReason } from "../agents/runtime.js";

// Demo clock. The local network advances about 72 seconds of chain time per block, so one
// calendar day is mapped to 72 chain seconds (one block). Real deployments use real durations.
const DAY_SECS = 72n;

const fmt = (c: bigint) => `$${(Number(c) / 100).toFixed(2)}`;
const step = (s: string) => console.log(`\n▶ ${s}`);
const note = (s: string) => console.log(`    ${s}`);

async function main() {
  console.log("relnet demo: agents make the deal, people sign it, contracts enforce it");
  console.log("Local test network. Fictional entities. No real funds.");

  step("1. Each company's person sets a mandate; their agents negotiate inside it");
  const B = EXAMPLE_BUYER_MANDATE;
  const S = EXAMPLE_SUPPLIER_MANDATE;
  note(`${B.company} (buyer) accepts price ${fmt(B.ranges.price_cents.min)} to ${fmt(B.ranges.price_cents.max)}, ship-by 7 to 21 days, late penalty up to 20%.`);
  note(`${S.company} (supplier) accepts price ${fmt(S.ranges.price_cents.min)} to ${fmt(S.ranges.price_cents.max)}, ship-by 10 to 28 days, late penalty at most 10%.`);
  // Two separate agents, each holding only its own mandate, talk over A2A (signed Agent Cards,
  // bearer tokens and signed offers). Each pins the other's key from a "deal code".
  const buyerKey = await createIdentity();
  const supplierKey = await createIdentity();
  const dealId = randomUUID();
  const events: string[] = [];
  const onEvent = (e: { who: string; text: string }) => events.push(`[${e.who}] ${e.text}`);
  const buyerPin = await pinPeer({ fingerprint: buyerKey.fingerprint, publicJwk: buyerKey.publicJwk, url: "" });
  const supplierAgent = await startResponder({ side: "supplier", mandate: S, identity: supplierKey, peer: buyerPin, dealId, name: "supplier agent", onEvent });
  const supplierPin = await pinPeer({ fingerprint: supplierKey.fingerprint, publicJwk: supplierKey.publicJwk, url: supplierAgent.url });
  note(`Deal code: buyer agent key ${buyerKey.fingerprint.slice(0, 12)}..., supplier agent key ${supplierKey.fingerprint.slice(0, 12)}... (people confirm these out-of-band)`);
  const outcome = await negotiateOverA2A({ side: "buyer", mandate: B, identity: buyerKey, peer: supplierPin, dealId, name: "buyer agent", onEvent });
  await supplierAgent.close();
  if (!outcome.ok) throw new Error(outcome.reason);
  for (const e of events.filter((x) => /verified|accepted|agreement/.test(x))) note(e);
  note(`Agents agreed at round ${outcome.rounds} over A2A. Neither agent saw the other's limits. No model chose any number.`);
  const deal = { terms: outcome.terms };
  note(`Each side checks the result against its own limits: buyer ${withinLimits("buyer", B, deal.terms) ? "within limits" : "OUT"}, supplier ${withinLimits("supplier", S, deal.terms) ? "within limits" : "OUT"}.`);

  step("2. The terms a person reads before signing (generated by code from the exact values)");
  for (const line of summarizeTerms(deal.terms)) note(`- ${line}`);
  const onChain: Terms = scaleTime(deal.terms, DAY_SECS);
  note(`Demo clock: one day is compressed to ${DAY_SECS} chain seconds (about one block on the local network), so the ship-by deadline is ${onChain.lead_time_secs}s of chain time.`);

  step("3. Deploy the agreement. The negotiated terms start as a proposal, not as a contract");
  const w = await setup(onChain, false);
  const log = new DecisionLog();
  log.onAdd = (d) =>
    note(`[${d.agent}] ${d.action}${d.detail ? ` -> ${d.result.toUpperCase()}: ${d.detail}` : d.result === "accepted" ? " -> accepted" : ""}`);
  try {
    await w.agreement.methods.place_call_off(1n, 40n, onChain.price_cents).send(w.o(w.buyerAgent));
    note("UNEXPECTED: an order was accepted before sign-off");
  } catch (e) {
    note(`Buyer agent tries to order before anyone has signed -> REJECTED: ${revertReason(e)}`);
  }

  step("4. The person at each company signs; agents cannot");
  try {
    await w.agreement.methods.approve_terms(await w.proposalId()).send(w.o(w.supplierAgent));
    note("UNEXPECTED: an agent approved the terms");
  } catch (e) {
    note(`Supplier agent tries to approve -> REJECTED: ${revertReason(e)}`);
  }
  const proposal = await w.proposalId();
  await w.agreement.methods.approve_terms(proposal).send(w.o(w.buyer));
  note(`${B.company}'s person approved proposal #${proposal}.`);
  await w.agreement.methods.approve_terms(proposal).send(w.o(w.supplier));
  note(`${S.company}'s person approved proposal #${proposal}. The agreement is now active.`);

  step("5. Agents run the deal. Three orders; one ships late");
  const lat: number[] = [];
  const timed = async (fn: () => Promise<unknown>) => {
    const t = Date.now();
    await fn();
    lat.push(Date.now() - t);
  };
  const price = onChain.price_cents;
  const rows: { id: bigint; qty: bigint; value: bigint; late: string; paid: bigint }[] = [];

  async function fund(id: bigint, qty: bigint) {
    await w.token.methods.transfer_public(w.escrow.address, qty * price).send(w.o(w.buyerAgent));
    await w.escrow.methods.fund_call_off(id, w.carrier).send(w.o(w.buyerAgent));
  }
  async function finish(id: bigint, qty: bigint) {
    await w.receive(id);
    await w.escrow.methods.attest_inspected(id).send(w.o(w.buyerAgent));
    const total = (await w.escrow.methods.get_total(id).simulate({ from: w.buyer })).result as bigint;
    // Delivery status is read from what the escrow actually paid, not assumed.
    rows.push({ id, qty, value: qty * price, late: total < qty * price ? "LATE" : "on time", paid: total });
  }

  // Order 2 goes first; its supplier is slow and ships last, after its deadline.
  await timed(() => buyerPlacesOrder(w, log, 2n, 30n, price, "stock is running low"));
  await fund(2n, 30n);
  note("[supplier agent] order #2: production is delayed, shipment will wait");

  // Order 1: on time.
  await timed(() => buyerPlacesOrder(w, log, 1n, 40n, price, "weekly replenishment"));
  await fund(1n, 40n);
  await timed(() => w.ship(1n));
  log.add({ agent: "supplier agent", action: "order #1: shipped before the deadline", why: "goods ready", result: "accepted" });
  await finish(1n, 40n);

  // Order 3: the buyer agent makes a typo (400 units instead of 40) and corrects itself.
  const o3 = await buyerPlacesOrder(w, log, 3n, 400n, price, "weekly replenishment (unit mix-up: typed 400)", 40n);
  await fund(3n, o3.qty);
  await timed(() => w.ship(3n));
  log.add({ agent: "supplier agent", action: "order #3: shipped before the deadline", why: "goods ready", result: "accepted" });
  await finish(3n, o3.qty);

  // Order 2 ships once it is at least two full late periods past its deadline.
  const rec2 = (await w.agreement.methods.get_call_off(2n).simulate({ from: w.buyer })).result as any;
  const target = BigInt(rec2.ship_by) + BigInt(rec2.grace_secs) + 2n * onChain.late_period_secs;
  while ((await w.chainNow()) < target) await w.tick();
  await timed(() => w.ship(2n));
  const cut = 30n * price - ((await w.escrow.methods.get_total(2n).simulate({ from: w.buyer })).result as bigint);
  log.add({
    agent: "escrow",
    action: `order #2 shipped late: the signed rule cut the price by ${fmt(cut)} and refunded the buyer`,
    why: "late_bps_per_period and late_cap_bps from the signed terms; nobody chose this amount",
    result: "info",
  });
  await finish(2n, 30n);

  console.log("\n    order  units  list value  delivery  supplier paid");
  for (const r of rows.sort((a, b) => Number(a.id - b.id))) {
    console.log(`    #${r.id}     ${String(r.qty).padEnd(5)}  ${fmt(r.value).padEnd(10)}  ${r.late.padEnd(8)}  ${fmt(r.paid)}`);
  }

  step("6. Zero-knowledge proof: the supplier proves its on-time rate without revealing orders");
  await w.tick();
  await w.tick();
  for (const r of rows) {
    await w.pp.methods.absorb_outcome(r.id, r.late === "on time").send(w.o(w.supplier));
  }
  note("Supplier folded 3 verified outcomes into one private note (counts stay off-chain).");
  try {
    await w.pp.methods.prove_on_time_rate(95n).send(w.o(w.supplier));
    note("UNEXPECTED: proved 95%");
  } catch (e) {
    note(`Prove at least 95% on time -> REJECTED: ${revertReason(e)}`);
  }
  await timed(() => w.pp.methods.prove_on_time_rate(60n).send(w.o(w.supplier)));
  const proven = (await w.pp.methods.get_proven_threshold(w.supplier).simulate({ from: w.buyer })).result;
  note(`Prove at least 60% on time -> OK. Public record: >= ${proven}%. Counts, dates and quantities are not revealed.`);

  step("7. Hostile and mistaken agents attack the same deployment");
  await w.agreement.methods.place_call_off(90n, 20n, price).send(w.o(w.buyerAgent));
  const attacks: [string, () => Promise<unknown>][] = [
    ["Order 9999 units (outside the signed band)", () => w.agreement.methods.place_call_off(91n, 9999n, price).send(w.o(w.supplierAgent))],
    ["Order at 1 cent (not the signed price)", () => w.agreement.methods.place_call_off(92n, 50n, 1n).send(w.o(w.supplierAgent))],
    ["A stranger places an order", () => w.agreement.methods.place_call_off(93n, 50n, price).send(w.o(w.outsider))],
    [
      "An agent approves terms on its own",
      async () => {
        const t = (await w.agreement.methods.get_terms().simulate({ from: w.buyer })).result as Terms;
        await w.agreement.methods.propose_terms(t).send(w.o(w.buyerAgent)); // open proposal to attack
        await w.agreement.methods.approve_terms(await w.proposalId()).send(w.o(w.buyerAgent));
      },
    ],
    ["A stranger mints tokens", () => w.token.methods.mint_publicly(w.outsider, 1_000_000n).send(w.o(w.outsider))],
    ["Forge an on-time delivery record", () => w.pp.methods.record_outcome(999n, true).send(w.o(w.supplierAgent))],
    ["Open escrow with no money sent", () => w.escrow.methods.fund_call_off(90n, w.carrier).send(w.o(w.buyerAgent))],
    ["A stranger confirms inspection", () => w.escrow.methods.attest_inspected(90n).send(w.o(w.outsider))],
    ["A stranger acts as arbiter", () => w.escrow.methods.arbiter_resolve(90n, w.outsider, 100n).send(w.o(w.outsider))],
  ];
  let blocked = 0;
  console.log("\n    attack                                              baseline ledger   relnet");
  for (const [name, run] of attacks) {
    let result = "BLOCKED";
    try {
      await run();
      result = "ACCEPTED";
    } catch {
      blocked++;
    }
    console.log(`    ${name.padEnd(52)}${"accepted".padEnd(18)}${result}`);
  }
  note(`\nrelnet blocked ${blocked}/${attacks.length}. The baseline is a trust-the-agent ledger with no on-chain rules, which accepts all ${attacks.length} (modeled, not run).`);

  const sorted = [...lat].sort((a, b) => a - b);
  step("8. Measured on this machine (local sandbox; proving mode not verified, so treat as execution latency)");
  note(`${lat.length} timed operations: median ${(sorted[Math.floor(sorted.length / 2)] / 1000).toFixed(1)}s, max ${(sorted[sorted.length - 1] / 1000).toFixed(1)}s`);
  note("Numbers are from one run on one laptop; they are not a benchmark.");
  console.log("\nDone.");
  process.exit(0);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
