// Deal terms: the fixed rule vocabulary an agent may compose. Mirrors `Terms` in
// contracts/agreement/src/main.nr. The contract re-checks every bound, so this module
// is for catching mistakes early and for giving humans a summary they can sign.
// Money is integer cents, rates are basis points (1 bp = 0.01%), durations are seconds.

export interface Terms {
  price_cents: bigint;
  volume_min: bigint;
  volume_max: bigint;
  ship_bps: bigint;
  receive_bps: bigint;
  lead_time_secs: bigint;
  grace_secs: bigint;
  late_period_secs: bigint;
  late_bps_per_period: bigint;
  late_cap_bps: bigint;
  cancel_after_secs: bigint;
  deemed_acceptance_secs: bigint;
}

export interface TermField {
  key: keyof Terms;
  unit: "cents" | "units" | "bps" | "seconds";
  description: string;
  min: bigint;
}

export const TERM_FIELDS: TermField[] = [
  { key: "price_cents", unit: "cents", min: 1n, description: "Price per unit." },
  { key: "volume_min", unit: "units", min: 1n, description: "Smallest allowed call-off quantity." },
  { key: "volume_max", unit: "units", min: 1n, description: "Largest allowed call-off quantity. Must be >= volume_min." },
  { key: "ship_bps", unit: "bps", min: 0n, description: "Share of the call-off value paid when shipment is attested." },
  { key: "receive_bps", unit: "bps", min: 0n, description: "Share paid when receipt is attested. ship_bps + receive_bps <= 10000. The remainder is paid at inspection." },
  { key: "lead_time_secs", unit: "seconds", min: 0n, description: "Time from placing a call-off to its ship-by deadline." },
  { key: "grace_secs", unit: "seconds", min: 0n, description: "Time after ship-by before any price reduction starts." },
  { key: "late_period_secs", unit: "seconds", min: 1n, description: "Length of one late period (86400 = one day)." },
  { key: "late_bps_per_period", unit: "bps", min: 0n, description: "Price reduction per full late period." },
  { key: "late_cap_bps", unit: "bps", min: 0n, description: "Maximum total price reduction. At most 10000." },
  { key: "cancel_after_secs", unit: "seconds", min: 1n, description: "Time after ship-by plus grace when the buyer may cancel unshipped goods for a full refund." },
  { key: "deemed_acceptance_secs", unit: "seconds", min: 1n, description: "Time after receipt when buyer silence counts as acceptance." },
];

const DAY = 86400n;

/** A realistic example. Agents should start from this and change values, not keys. */
export const EXAMPLE_TERMS: Terms = {
  price_cents: 500n,
  volume_min: 10n,
  volume_max: 100n,
  ship_bps: 3000n,
  receive_bps: 5000n,
  lead_time_secs: 14n * DAY,
  grace_secs: 1n * DAY,
  late_period_secs: DAY,
  late_bps_per_period: 200n,
  late_cap_bps: 1000n,
  cancel_after_secs: 14n * DAY,
  deemed_acceptance_secs: 7n * DAY,
};

const MAX_U64 = (1n << 64n) - 1n;

/** Parse untrusted input (for example JSON an LLM produced) into Terms, or throw. */
export function parseTerms(raw: unknown): Terms {
  if (typeof raw !== "object" || raw === null) throw new Error("Terms must be an object");
  const obj = raw as Record<string, unknown>;
  const allowed = new Set<string>(TERM_FIELDS.map((f) => f.key));
  for (const k of Object.keys(obj)) {
    if (!allowed.has(k)) throw new Error(`Unknown term "${k}". Allowed: ${[...allowed].join(", ")}`);
  }
  const out: Partial<Terms> = {};
  for (const f of TERM_FIELDS) {
    const v = obj[f.key];
    if (typeof v === "number" && !Number.isSafeInteger(v)) throw new Error(`${f.key} must be an integer`);
    if (typeof v !== "number" && typeof v !== "string" && typeof v !== "bigint") {
      throw new Error(`${f.key} is required`);
    }
    if (typeof v === "string" && !/^\d+$/.test(v)) throw new Error(`${f.key} must be a whole number`);
    const n = BigInt(v);
    if (n < 0n || n > MAX_U64) throw new Error(`${f.key} is out of range`);
    out[f.key] = n;
  }
  return out as Terms;
}

/** Returns a list of problems; empty means the terms satisfy the contract's checks. */
export function validateTerms(t: Terms): string[] {
  const e: string[] = [];
  for (const f of TERM_FIELDS) {
    if (t[f.key] < f.min) e.push(`${f.key} must be at least ${f.min}`);
  }
  if (t.volume_min > t.volume_max) e.push("volume_min must not exceed volume_max");
  if (t.ship_bps + t.receive_bps > 10000n) e.push("ship_bps + receive_bps must not exceed 10000");
  if (t.late_cap_bps > 10000n) e.push("late_cap_bps must not exceed 10000");
  return e;
}

const cents = (c: bigint) => `$${(Number(c) / 100).toFixed(2)}`;
const pct = (bps: bigint) => `${(Number(bps) / 100).toString()}%`;
function dur(secs: bigint): string {
  if (secs >= DAY) {
    const days = Math.round((Number(secs) / Number(DAY)) * 100) / 100;
    return `${days} day${days === 1 ? "" : "s"}`;
  }
  if (secs % 3600n === 0n && secs >= 3600n) return `${secs / 3600n} hours`;
  return `${secs} seconds`;
}

/**
 * Plain-language summary generated by code from the exact values, never by a model.
 * This is what a person reads before signing.
 */
export function summarizeTerms(t: Terms): string[] {
  return [
    `Price: ${cents(t.price_cents)} per unit.`,
    `Each order must be between ${t.volume_min} and ${t.volume_max} units.`,
    `Payment: ${pct(t.ship_bps)} when shipment is confirmed, ${pct(t.receive_bps)} when receipt is confirmed, ${pct(10000n - t.ship_bps - t.receive_bps)} when the buyer inspects.`,
    `Ship-by deadline: ${dur(t.lead_time_secs)} after the order.`,
    t.late_bps_per_period === 0n
      ? "No price reduction for late shipment."
      : `Late shipment: after a ${dur(t.grace_secs)} grace period, the price drops ${pct(t.late_bps_per_period)} for every full ${dur(t.late_period_secs)} late, up to ${pct(t.late_cap_bps)}. The reduction is refunded to the buyer automatically.`,
    `If nothing ships, the buyer may cancel for a full refund ${dur(t.cancel_after_secs)} after the deadline plus grace.`,
    `If the buyer does not inspect within ${dur(t.deemed_acceptance_secs)} of receipt, the goods count as accepted and the rest is paid.`,
  ];
}

export function termsToContractArg(t: Terms) {
  return { ...t };
}
